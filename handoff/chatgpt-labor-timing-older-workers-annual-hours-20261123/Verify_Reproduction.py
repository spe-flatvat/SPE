"""Compare a separately executed regeneration with delivered originals (no model changes)."""
import argparse,json,hashlib
from pathlib import Path

def run(packet,replay):
 generated=[];copied=[]
 for f in sorted(replay.rglob('*')):
  if not f.is_file() or '__pycache__' in f.parts:continue
  rel=f.relative_to(replay).as_posix();b=f.read_bytes();original=packet/rel
  assert original.is_file(),('not in original packet',rel)
  assert b==original.read_bytes(),('regenerated bytes differ',rel)
  r=dict(path=rel,size=len(b),sha256=hashlib.sha256(b).hexdigest(),bytes_match=True)
  (copied if rel.startswith('Source_Originals/') else generated).append(r)
 result=dict(status='PASS',separate_output=True,regenerated_files=len(generated),copied_source_originals=len(copied),copied_not_counted_as_generated=True,regenerated=generated,copied_inputs=copied)
 (packet/'Reproduction_Verification.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n');print(json.dumps({k:v for k,v in result.items() if not isinstance(v,list)}))
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--packet',type=Path,required=True);p.add_argument('--replay',type=Path,required=True);a=p.parse_args();run(a.packet,a.replay)
